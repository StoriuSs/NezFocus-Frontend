// Builds the Content-Security-Policy for the production nginx image.
//
//   node scripts/csp.mjs dist > csp.conf.template
//
// Run in the Docker build, after `vite build`. What the build knows goes in
// now: the inline scripts of every built HTML page, by hash (index.html's
// theme script). What only the server knows — the API, error-tracking and
// image origins — is left as a placeholder, and the
// container fills it in when it starts, from the same settings it writes into
// config.js (nginx/40-runtime-config.sh). Nothing is hand-maintained, so the
// policy can't drift from the build or from the settings.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Inline `<script>` bodies (no src attribute), exactly as the browser hashes
 * them. HTML parsing turns CRLF and lone CR into LF before a script's text is
 * hashed, so the file bytes must be normalised the same way: a checkout with
 * Windows line endings otherwise produced hashes no browser matched, and the
 * page's own scripts were blocked.
 */
export function inlineScripts(html) {
    const normalised = html.replace(/\r\n?/g, '\n')
    return [...normalised.matchAll(/<script\b(?![^>]*\bsrc\s*=)[^>]*>([\s\S]*?)<\/script>/gi)].map((match) => match[1])
}

/**
 * The placeholders the container replaces at start, each on its own line in
 * nginx/40-runtime-config.sh. They are not valid CSP sources, so a policy that
 * still holds one is a bug that shows in the browser rather than a silently
 * permissive header.
 */
export const PLACEHOLDERS = {
    api: '__API_ORIGIN__',
    errorTracking: '__SENTRY_ORIGIN__',
    images: '__EXTRA_IMAGE_ORIGINS__'
}

/**
 * The policy with a placeholder for every origin only the server knows.
 *
 * @param {string[]} pages the HTML of every page the server can return
 * @returns {string} the policy, directives separated by "; "
 */
export function cspTemplate(pages) {
    return policy({
        api: PLACEHOLDERS.api,
        errorTracking: [PLACEHOLDERS.errorTracking],
        extraImages: [PLACEHOLDERS.images],
        pages
    })
}

/**
 * Cloudflare Turnstile's widget: its script, and the frame it draws the
 * challenge in. Always allowed, because whether Turnstile is on is only known
 * at runtime (the API's GET /auth/options); this one origin, never a wildcard.
 */
export const TURNSTILE_ORIGIN = 'https://challenges.cloudflare.com'

/** The policy from origins that are already resolved (or placeholders). */
function policy({ api, errorTracking, extraImages, pages }) {
    const hashes = pages
        .flatMap(inlineScripts)
        .map((body) => `'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`)
    const unique = (...sources) => [...new Set(sources)].join(' ')

    return [
        "default-src 'self'",
        `script-src ${unique("'self'", TURNSTILE_ORIGIN, ...hashes)}`,
        // Radix and sonner position elements with inline style attributes.
        "style-src 'self' 'unsafe-inline'",
        // Avatars come from the API (local storage) or from a bucket whose host
        // is only known per deployment (S3, R2, RustFS): any https source is
        // allowed, and a bucket served over plain http — local RustFS, say —
        // must be listed in CSP_IMG_SRC.
        `img-src ${unique("'self'", 'data:', 'blob:', 'https:', api, ...extraImages)}`,
        "font-src 'self' data:",
        `connect-src ${unique("'self'", api, ...errorTracking)}`,
        // One frame only: Turnstile's challenge. Something else that needs
        // one (a payment form) adds its origin here, not a wildcard.
        `frame-src ${TURNSTILE_ORIGIN}`,
        "frame-ancestors 'self'",
        "form-action 'self'",
        "base-uri 'self'",
        "object-src 'none'"
    ].join('; ')
}

/** Every .html file under a directory. */
export function readPages(dir) {
    return readdirSync(dir, { recursive: true })
        .filter((file) => String(file).endsWith('.html'))
        .map((file) => readFileSync(join(dir, String(file)), 'utf8'))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const [distDir] = process.argv.slice(2)
    if (!distDir) {
        console.error('Usage: node scripts/csp.mjs dist > csp.conf.template')
        process.exit(1)
    }
    console.log('# Generated by scripts/csp.mjs during the image build. Do not edit.')
    console.log('# The __…__ placeholders are filled in at container start by')
    console.log('# /docker-entrypoint.d/40-runtime-config.sh.')
    console.log(`add_header Content-Security-Policy "${cspTemplate(readPages(distDir))}" always;`)
}
